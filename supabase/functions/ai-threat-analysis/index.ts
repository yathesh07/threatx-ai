import { serve } from "https://deno.land/std@0.168.0/http/server.ts";

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers": "authorization, x-client-info, apikey, content-type, x-supabase-client-platform, x-supabase-client-platform-version, x-supabase-client-runtime, x-supabase-client-runtime-version",
};

serve(async (req) => {
  if (req.method === "OPTIONS") return new Response(null, { headers: corsHeaders });

  try {
    const { messages, mode } = await req.json();
    const LOVABLE_API_KEY = Deno.env.get("LOVABLE_API_KEY");
    if (!LOVABLE_API_KEY) throw new Error("LOVABLE_API_KEY is not configured");

    const systemPrompts: Record<string, string> = {
      "threat-analysis": `You are ThreatX AI, a cybersecurity threat analysis expert. Analyze the given threat data and provide:
1. A clear, beginner-friendly explanation of what this threat is
2. Why it's dangerous (impact assessment)
3. Step-by-step remediation actions
4. Prevention tips for the future
Keep responses structured with markdown headers. Be thorough but accessible to beginners.`,
      "chatbot": `You are ThreatX Security Assistant, a friendly and knowledgeable cybersecurity chatbot. You help users understand:
- Security threats and how to handle them
- Best practices for staying safe online
- How to interpret scan results and alerts
- General cybersecurity concepts

Always be beginner-friendly. Use analogies and simple language. If asked about something dangerous, always recommend safe practices.
Format responses with markdown for readability.`,
      "executive-summary": `You are a corporate cybersecurity report writer. Generate a professional executive summary for the given incident data. Include:
- Threat classification and severity assessment
- Business impact analysis
- Recommended immediate actions
- Long-term mitigation strategy
Keep the tone professional and suitable for C-level executives.`,
    };

    const systemPrompt = systemPrompts[mode] || systemPrompts["chatbot"];

    const response = await fetch("https://ai.gateway.lovable.dev/v1/chat/completions", {
      method: "POST",
      headers: {
        Authorization: `Bearer ${LOVABLE_API_KEY}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        model: "google/gemini-3-flash-preview",
        messages: [
          { role: "system", content: systemPrompt },
          ...messages,
        ],
        stream: true,
      }),
    });

    if (!response.ok) {
      if (response.status === 429) {
        return new Response(JSON.stringify({ error: "Rate limit exceeded. Please try again in a moment." }), {
          status: 429,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      if (response.status === 402) {
        return new Response(JSON.stringify({ error: "AI credits exhausted. Please add credits in Settings → Workspace → Usage." }), {
          status: 402,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      const t = await response.text();
      console.error("AI gateway error:", response.status, t);
      return new Response(JSON.stringify({ error: "AI analysis failed" }), {
        status: 500,
        headers: { ...corsHeaders, "Content-Type": "application/json" },
      });
    }

    return new Response(response.body, {
      headers: { ...corsHeaders, "Content-Type": "text/event-stream" },
    });
  } catch (e) {
    console.error("ai-threat-analysis error:", e);
    return new Response(JSON.stringify({ error: e instanceof Error ? e.message : "Unknown error" }), {
      status: 500,
      headers: { ...corsHeaders, "Content-Type": "application/json" },
    });
  }
});
